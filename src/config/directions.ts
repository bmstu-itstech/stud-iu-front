export type DirectionActivityValue =
  | 'programming'
  | 'event_planning'
  | 'content_creation'
  | 'team_building'
  | 'partnership'
  | 'event_tech_support'

export interface DirectionInfoCard {
  name: string
  description?: string
}

export type DirectionBlock =
  | { type: 'text'; title?: string; paragraphs: string[] }
  | { type: 'list'; title: string; intro?: string; items: string[] }
  | {
      type: 'cards'
      title: string
      intro?: string
      columns?: 2 | 3 | 4
      cards: DirectionInfoCard[]
    }

export interface Direction {
  slug: string
  title: string
  lead: string | null
  tagline: string
  activityValue: DirectionActivityValue
  joinNote?: string
  blocks: DirectionBlock[]
}

